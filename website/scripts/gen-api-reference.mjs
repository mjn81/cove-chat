// Generates docs/api/rest.md from the swaggo output (backend/docs/swagger.json): one table per tag with
// method, path, summary and the access tier declared in each handler's `**Access:**` line.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, '../backend/docs/swagger.json');
const out = resolve(root, 'src/content/docs/docs/api/rest.md');

const spec = JSON.parse(readFileSync(src, 'utf8'));
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
/** @type {Map<string, {method: string, path: string, summary: string, access: string}[]>} */
const byTag = new Map();

for (const [path, ops] of Object.entries(spec.paths ?? {})) {
  for (const m of METHODS) {
    const op = ops[m];
    if (!op) continue;
    const access = /\*\*Access:\*\*\s*([^\n]+)/.exec(op.description ?? '')?.[1]?.trim() ?? (op.security ? 'Authenticated' : 'Public');
    const tag = op.tags?.[0] ?? 'other';
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push({ method: m.toUpperCase(), path, summary: op.summary ?? '', access });
  }
}

const esc = (s) => s.replace(/\|/g, '\\|');
let md = `---
title: REST API
description: Every REST endpoint with its access tier. Generated from the backend's Swagger output.
---

{/* Generated by website/scripts/gen-api-reference.mjs from backend/docs/swagger.json. Do not edit by hand. */}

The API is JSON over HTTP. Web clients authenticate with an httpOnly session cookie plus an \`X-CSRF-Token\` header on mutations; the desktop app uses a Bearer token.

## Conventions

- **Errors** use one envelope: \`{ "error": "message", "code": "stable_machine_code", "details": {} }\`. Branch on \`code\` (or the HTTP status), never on the message. \`details\` is optional. The code registry is in the [API standard](/docs/api/standard/#error-envelope).
- **Headers.** Clients send \`X-Cove-Client: <platform>/<version> (api <n>)\`. Every response carries \`X-Cove-API-Version\` and \`X-Cove-Server-Version\`.
- **Paging.** Lists that can grow without bound answer \`{ "items": [...], "next_cursor": "..." }\` and take \`limit\` (default 50, max 100) and \`cursor\` (opaque; an invalid value is a 400 \`validation_failed\`). \`next_cursor\` is empty on the last page. See [Pagination](/docs/api/standard/#pagination).
- **Compatibility.** \`GET /api/version\` returns \`version\`, \`udp_port\`, \`api_version\`, \`min_client_version\` and \`capabilities\`. Gate features on \`capabilities\`, not on version numbers.
- **Evolution.** Additive changes (new fields, endpoints, events) never bump \`api_version\`; clients must ignore what they do not know. Details in the [API standard](/docs/api/standard/).

When the server runs with \`server.dev = true\`, an interactive Swagger UI is served at \`/api/docs/\`.

`;

for (const [tag, rows] of [...byTag].sort(([a], [b]) => a.localeCompare(b))) {
  md += `## ${tag}\n\n| Method | Path | Summary | Access |\n| --- | --- | --- | --- |\n`;
  for (const r of rows) md += `| \`${r.method}\` | \`${r.path}\` | ${esc(r.summary)} | ${esc(r.access)} |\n`;
  md += '\n';
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`api reference: ${[...byTag.values()].reduce((n, r) => n + r.length, 0)} endpoints -> ${out}`);
