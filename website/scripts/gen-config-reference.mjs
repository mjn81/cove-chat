// Generates docs/configuration/reference.md from backend/config.toml.example so the docs cannot drift
// from the shipped config. Run with `pnpm gen` (wired into the Makefile as `make site/gen`).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, '../backend/config.toml.example');
const out = resolve(root, 'src/content/docs/docs/configuration/reference.md');

/** @type {{name: string, keys: {key: string, value: string, doc: string[], optional: boolean}[]}[]} */
const sections = [];
let current = null;
let buf = [];
let inCommentedTable = false;

for (const raw of readFileSync(src, 'utf8').split(/\r?\n/)) {
  const line = raw.trimEnd();
  const header = line.match(/^\[([\w.]+)\]$/);
  if (header) {
    current = { name: header[1], keys: [] };
    sections.push(current);
    buf = [];
    inCommentedTable = false;
    continue;
  }
  if (/^#\s*\[\[/.test(line)) {
    inCommentedTable = true;
    buf = [];
    continue;
  }
  if (line.trim() === '') {
    buf = [];
    continue;
  }
  const kv = line.match(/^(#\s*)?([a-z_][\w]*)\s*=\s*(.+)$/);
  if (kv && current && !(kv[1] && inCommentedTable)) {
    current.keys.push({ key: kv[2], value: kv[3].trim(), doc: buf, optional: Boolean(kv[1]) });
    buf = [];
    continue;
  }
  if (line.startsWith('#')) {
    const text = line.replace(/^#\s?/, '');
    // Banner rules like "# -- Registration ---" are decoration, not documentation.
    if (!/^[─-╿-]{2,}/.test(text) && !/^[─-╿]/.test(text)) buf.push(text);
  }
}

const esc = (s) => s.replace(/\|/g, '\\|');
let md = `---
title: config.toml reference
description: Every key in config.toml, with defaults and explanations. Generated from backend/config.toml.example.
---

{/* Generated by website/scripts/gen-config-reference.mjs. Do not edit by hand. */}

Copy \`backend/config.toml.example\` to \`config.toml\` next to the server binary (or mount it into the container). Keys not listed there use built-in defaults. Restart the server after editing the file unless the admin panel says the key applies live.

`;

for (const s of sections) {
  md += `## \`[${s.name}]\`\n\n`;
  for (const k of s.keys) {
    md += `### \`${s.name}.${k.key}\`\n\n`;
    md += `Default: \`${esc(k.value)}\`${k.optional ? ' (commented out in the example; optional)' : ''}\n\n`;
    const doc = k.doc.map((d) => d.trimEnd());
    if (doc.length) md += doc.map((d) => (/^\s{2,}|^["#]/.test(d) ? `    ${d.trim()}` : d)).join('\n').replace(/\n(    [^\n]+)/g, '\n$1') + '\n\n';
  }
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`config reference: ${sections.reduce((n, s) => n + s.keys.length, 0)} keys -> ${out}`);
